CREATE TABLE FGCRB555 (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DATA_INICIO DATE NOT NULL, DATA_FIM DATE,
  TAXA_ANUAL INTEGER NOT NULL CHECK (TAXA_ANUAL IN (3,4,5,6)),
  FONTE_DADO VARCHAR(20) NOT NULL, VERSAO_CARGA VARCHAR(40) NOT NULL,
  CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);
CREATE INDEX IDX_FGCRB555_VIGENCIA ON FGCRB555(DATA_INICIO, DATA_FIM);
CREATE TABLE FGCRB560 (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DATA_SBPC DATE, DATA_RECOLHIMENTO DATE, DATA_CREDITO_JAM DATE,
  CODIGO_LANCAMENTO VARCHAR(20), TIPO_CONTA VARCHAR(30),
  FONTE_DADO VARCHAR(20) NOT NULL, VERSAO_CARGA VARCHAR(40) NOT NULL
);
CREATE INDEX IDX_FGCRB560_DATAS ON FGCRB560(DATA_RECOLHIMENTO, DATA_CREDITO_JAM);
CREATE TABLE CONTA_ATUALIZACAO (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORIGEM VARCHAR(30) NOT NULL, DATA_BASE DATE NOT NULL, DATA_LIMITE DATE NOT NULL,
  SALDO_INICIAL DECIMAL(19,2) NOT NULL, TOTAL_DEPOSITOS_INICIAL DECIMAL(19,2),
  JAM_INFORMADO_INICIAL DECIMAL(19,2), SALDO_POS_JAM_INICIAL DECIMAL(19,2),
  SALDO_COMPLEMENTAR_INICIAL DECIMAL(19,2), PARAMETROS_JSON CLOB,
  STATUS VARCHAR(20) NOT NULL, CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (DATA_LIMITE >= DATA_BASE)
);
CREATE TABLE RESULTADO_ATUALIZACAO (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTA_ATUALIZACAO_ID BIGINT NOT NULL, SALDO_FINAL DECIMAL(19,2) NOT NULL,
  JAM_TOTAL DECIMAL(19,2) NOT NULL, DATA_FINAL_PROCESSADA DATE,
  DADOS_DEMONSTRACAO BOOLEAN NOT NULL, VERSAO_CARGA VARCHAR(40),
  CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_RESULTADO_CONTA FOREIGN KEY (CONTA_ATUALIZACAO_ID) REFERENCES CONTA_ATUALIZACAO(ID)
);
CREATE TABLE HISTORICO_ATUALIZACAO (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RESULTADO_ID BIGINT NOT NULL, SEQUENCIA INTEGER NOT NULL, DATA_COEFICIENTE DATE NOT NULL,
  TAXA_ANUAL INTEGER NOT NULL, COEFICIENTE_APLICADO DECIMAL(20,12) NOT NULL,
  BASE_CALCULO DECIMAL(19,2) NOT NULL, SALDO_ANTERIOR DECIMAL(19,2) NOT NULL,
  JAM_PERIODO DECIMAL(19,2) NOT NULL, SALDO_POSTERIOR DECIMAL(19,2) NOT NULL,
  REGRA_ESPECIAL VARCHAR(100), OBSERVACAO VARCHAR(500),
  CONSTRAINT FK_HISTORICO_RESULTADO FOREIGN KEY (RESULTADO_ID) REFERENCES RESULTADO_ATUALIZACAO(ID),
  CONSTRAINT UK_HISTORICO_SEQUENCIA UNIQUE (RESULTADO_ID, SEQUENCIA)
);
CREATE INDEX IDX_HISTORICO_RESULTADO ON HISTORICO_ATUALIZACAO(RESULTADO_ID, SEQUENCIA);
