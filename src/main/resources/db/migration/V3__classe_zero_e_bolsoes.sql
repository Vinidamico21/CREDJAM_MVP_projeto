-- Correções de aderência ao documento de regras do JAM:
--  1) Classe/coeficiente 0% (somente Atualização Monetária / TR), equivalente a
--     VAL-COEFICIENTE-0 do COBOL. Até então a tabela só tinha COEF_3..COEF_6.
--  2) Permitir TAXA_ANUAL = 0 na evolução de taxas (FGCRB555), já que a classe 0%
--     passa a ser representável.

-- 1) Nova coluna COEF_0 na tabela de coeficientes mensais (FGCRB550).
ALTER TABLE FGCRB550 ADD COLUMN COEF_0 DECIMAL(20,12);

-- Backfill determinístico da carga demonstrativa: coeficiente 0% = somente TR.
-- Na carga MOCK os coeficientes guardam o INCREMENTO (coeficiente - 1); como a
-- carga fictícia não tem série de TR, usa-se 0 (meses sem rendimento), coerente
-- com o exemplo 4 do documento (TR zero -> coeficiente 1,000000 -> sem rendimento).
UPDATE FGCRB550 SET COEF_0 = 0.000000000000 WHERE COEF_0 IS NULL;

-- A coluna passa a ser obrigatória, como as demais.
ALTER TABLE FGCRB550 ALTER COLUMN COEF_0 SET NOT NULL;

-- 2) Recriação da FGCRB555 para que o CHECK de TAXA_ANUAL aceite a classe 0%.
--    A tabela não possui chaves estrangeiras apontando para ela; recriar é seguro
--    e evita depender do nome auto-gerado do CHECK original.
CREATE TABLE FGCRB555_NOVA (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DATA_INICIO DATE NOT NULL, DATA_FIM DATE,
  TAXA_ANUAL INTEGER NOT NULL CHECK (TAXA_ANUAL IN (0,3,4,5,6)),
  FONTE_DADO VARCHAR(20) NOT NULL, VERSAO_CARGA VARCHAR(40) NOT NULL,
  CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);
INSERT INTO FGCRB555_NOVA (ID, DATA_INICIO, DATA_FIM, TAXA_ANUAL, FONTE_DADO, VERSAO_CARGA)
  SELECT ID, DATA_INICIO, DATA_FIM, TAXA_ANUAL, FONTE_DADO, VERSAO_CARGA FROM FGCRB555;
DROP TABLE FGCRB555;
ALTER TABLE FGCRB555_NOVA RENAME TO FGCRB555;
CREATE INDEX IDX_FGCRB555_VIGENCIA ON FGCRB555(DATA_INICIO, DATA_FIM);
